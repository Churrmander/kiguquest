    height: 5,
    glyph: (ch) => PICO[ch] || PICO[String(ch).toUpperCase()] || PICO['?'],
    width(s, sp) {
      sp = sp === undefined ? 1 : sp;
      let w = 0;
      for (const ch of String(s)) w += pico.glyph(ch)[0].length + sp;
      return Math.max(0, w - sp);
    },
