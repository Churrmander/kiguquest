    drake: (T, b, k, n, o) => { o({ t: 0, dur: T, ch: 'saw', f: Math.max(60, b / 2), f2: Math.max(55, b / 2.4), vol: 0.24 * k, env: 'swell', lp: 700, vib: { rate: 16, depth: 3 } }); n(0, T, 420, 220, 0.2 * k, 'swell'); },
